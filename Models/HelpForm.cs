using System;
using System.Windows.Forms;

namespace Kinis
{
    public partial class HelpForm : Form
    {
        public HelpForm()
        {
            InitializeComponent();

            // Загружаем текст справки
            helpTextBox.Text = GetHelpText();
        }

        private string GetHelpText()
        {
            return @"
СПРАВКА ПО РАБОТЕ С BPMN-РЕДАКТОРОМ KINIS
-----------------------------------------

1. ДОБАВЛЕНИЕ БЛОКОВ
• Перетаскивание из боковой панели.
• Двойной щелчок по блоку в боковой панели — блок появляется в центре холста.
• Создание горячими клавишами (назначение — в будущей версии).

2. ПЕРЕМЕЩЕНИЕ
• Захват блоков мышью.
• Групповое выделение — зажмите ЛКМ на пустом месте и тяните.

3. ИЗМЕНЕНИЕ РАЗМЕРА
• У выделенного блока появляются синие маркеры — потяните их для изменения размеров.

4. СОЕДИНЕНИЕ БЛОКОВ СТРЕЛКАМИ
• Создайте стрелку через панель.
• Потяните начало или конец стрелки — она привяжется к зелёным точкам блоков.

5. КРИВЫЕ СТРЕЛКИ
• Создаются через панель так же, как обычные стрелки.
• Можно редактировать форму кривой.

6. РЕДАКТИРОВАНИЕ ТЕКСТА
• Двойной клик на блок — появится окно редактирования текста.

7. МАСШТАБИРОВАНИЕ
• Ctrl + колесо мыши.
• Кнопки +, − и Reset в правом верхнем углу.
• Пределы: 25% – 500%.

8. ОТМЕНА / ПОВТОР
• Ctrl+Z — отмена.
• Ctrl+Y — повтор.
• Также доступны кнопки сверху.

9. РАБОТА С ЛИСТАМИ (CANVAS SHEETS)
• Поддержка нескольких рабочих листов (находится в разработке).

10. СОХРАНЕНИЕ И ЗАГРУЗКА
• Формат: *.bpmn.
• «Сохранить», «Сохранить как…», «Открыть».
• Числятся несохранённые изменения — программа предупредит перед закрытием.

11. ЭКСПОРТ В ИЗОБРАЖЕНИЕ
• Доступно сохранение окна в PNG/JPG/BMP.

12. ПАНЕЛЬ ФИГУР (SIDEBAR)
• Сворачивается кнопкой меню.
• Масштабируется по ширине.
• Поддерживает вертикальный скролл.

13. ВЫДЕЛЕНИЕ И НАВИГАЦИЯ
• Одно выделение — клик.
• Множественное — рамкой или Ctrl+клик.
• Перемещение всех выделенных элементов вместе.

14. ДОСТУПНЫЕ ТИПЫ ЭЛЕМЕНТОВ
• Комментарий  
• Задача  
• Развилка  
• Начальное событие  
• Промежуточное событие  
• Конечное событие  
• Объект данных  
• Хранилище данных  
• События сообщения (начальные, промежуточные, конечные)
• Ошибка (обработчик / инициатор)
• Отмена (обработчик / инициатор)
• Остановка
• Пул
• Стрелка и кривая стрелка

15. БУДУЩИЕ РАСШИРЕНИЯ
Окно справки подготовлено к расширению:
• Настройки автосохранения
• Настройки горячих клавиш
• Темы оформления
• Управление листами

-----------------------------------------
Спасибо, что используете KINIS!
";
        }
    }
}
